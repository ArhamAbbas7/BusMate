async function ensureCohortRow(inst) {
  return one(
    `INSERT INTO cohorts (code, start_date, end_date, signup_start, signup_end) VALUES ($1,$2,$3,$4,$5)
     ON CONFLICT (code, start_date) DO UPDATE SET end_date = EXCLUDED.end_date RETURNING *`,
    [inst.code, inst.start_date, inst.end_date, inst.signup_start, inst.signup_end],
  );
}

async function createOperator({ name, slug, pkg, price, payment, admin }) {
  const op = await one(
    `INSERT INTO operators (name, slug, package, contact_email, contact_phone, passenger_price, payment_instructions) VALUES ($1,$2,$3,$4,$5,$6,$7) RETURNING *`,
    [name, slug, pkg, admin.email, '+924200000000', price, JSON.stringify(payment)],
  );
  await query(`INSERT INTO users (email, password_hash, name, role, operator_id) VALUES ($1,$2,$3,'admin',$4)`, [admin.email, await hashPassword(admin.password), admin.name, op.id]);
  return op;
}

async function createRoute(opId, { code, name, towards, backward }) {
  const r = await one(
    `INSERT INTO routes (operator_id, code, name, towards_label, backward_label, path, live_token) VALUES ($1,$2,$3,$4,$5,$6,$7) RETURNING *`,
    [opId, code, name, towards, backward, JSON.stringify(PATHS[code] || []), crypto.randomBytes(12).toString('base64url')],
  );
  let n = 0;
  for (const cohort of ['A', 'B']) {
    for (const direction of ['towards', 'backward']) {
      n++;
      await query(`INSERT INTO route_groups (route_id, cohort, direction, wa_group_id, invite_link) VALUES ($1,$2,$3,$4,$5)`, [
        r.id,
        cohort,
        direction,
        `1203630000${code.replace(/\D/g, '').padStart(2, '0')}${n}${cohort === 'A' ? 1 : 2}@g.us`,
        `https://chat.whatsapp.com/DEMO${code}${cohort}${direction === 'towards' ? 'T' : 'B'}${crypto.randomBytes(4).toString('hex')}`,
      ]);
    }
  }
  return r;
}

async function createConductor(opId, name, phone, routeIds) {
  const c = await one(`INSERT INTO conductors (operator_id, name, phone) VALUES ($1,$2,$3) RETURNING *`, [opId, name, phone]);
  for (const rid of routeIds) await query(`INSERT INTO conductor_route_assignments (conductor_id, route_id) VALUES ($1,$2)`, [c.id, rid]);
  return c;
}

async function subscribe({ opId, routeId, cohort, name, phone, status, method = 'jazzcash', ref, proof = null, createdAt, confirmedBy = null }) {
  const sb = await one(`INSERT INTO subscribers (phone, name) VALUES ($1,$2) ON CONFLICT (phone) DO UPDATE SET name = EXCLUDED.name RETURNING *`, [phone, name]);
  const active = status === 'active' || status === 'expired';
  return one(
    `INSERT INTO subscriptions (operator_id, subscriber_id, route_id, cohort_id, status, payment_status, payment_method, payment_ref, proof_path, amount,
        subscription_start, subscription_expiry, confirmed_by, confirmed_at, invite_sent_at, expired_at, created_at, removed_from_groups)
     VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9,350,$10,$11,$12,$13,$13,$14,$15,$16) RETURNING *`,
    [
      opId,
      sb.id,
      routeId,
      cohort.id,
      status,
      active ? 'confirmed' : status === 'rejected' ? 'rejected' : 'pending',
      method,
      ref,
      proof,
      active ? cohort.start_date : null,
      active ? cohort.end_date : null,
      active ? confirmedBy : null,
      active ? createdAt : null,
      status === 'expired' ? createdAt : null,
      createdAt,
      false,
    ],
  );
}

async function createTrip(opId, conductor, route, direction, startedAt, minutes) {
  const pts = densify(direction === 'towards' ? route.path : [...route.path].reverse(), Math.max(2, Math.round((minutes * 2) / route.path.length)));
  const start = new Date(startedAt);
  const end = new Date(start.getTime() + (pts.length - 1) * 30000);
  const t = await one(
    `INSERT INTO trip_sessions (operator_id, conductor_id, route_id, direction, status, started_at, ended_at, last_ping_at, last_lat, last_lng, ping_count, end_reason)
     VALUES ($1,$2,$3,$4,'completed',$5,$6,$6,$7,$8,$9,'conductor') RETURNING id`,
    [opId, conductor.id, route.id, direction, start.toISOString(), end.toISOString(), pts.at(-1)[0], pts.at(-1)[1], pts.length],
  );
  const values = [];
  const params = [];
  pts.forEach((p, i) => {
    const b = params.length;
    params.push(t.id, p[0], p[1], 8 + Math.random() * 10, 6 + Math.random() * 6, new Date(start.getTime() + i * 30000).toISOString());
    values.push(`($${b + 1},$${b + 2},$${b + 3},$${b + 4},$${b + 5},$${b + 6})`);
  });
  await query(`INSERT INTO location_pings (trip_session_id, lat, lng, accuracy, speed, recorded_at) VALUES ${values.join(',')}`, params);
}

