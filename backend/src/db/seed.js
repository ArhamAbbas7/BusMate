function densify(path, stepsPerSegment) {
  const out = [];
  for (let i = 0; i < path.length - 1; i++) {
    const [a, b] = [path[i], path[i + 1]];
    for (let s = 0; s < stepsPerSegment; s++) {
      const f = s / stepsPerSegment;
      out.push([a[0] + (b[0] - a[0]) * f + (Math.random() - 0.5) * 0.0002, a[1] + (b[1] - a[1]) * f + (Math.random() - 0.5) * 0.0002]);
    }
  }
  out.push(path[path.length - 1]);
  return out;
}

